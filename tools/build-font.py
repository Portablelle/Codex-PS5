#!/usr/bin/env python3
"""Bake the bundled OFL font to native alpha masks; Pillow is a build-only tool."""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
font_path=ROOT/'vendor/manrope/Manrope.ttf'
# Private-use glyphs E000/E001 are the controller's L1/R1 shoulder badges.
extra_codes=[0x152,0x153,0x2013,0x2014,0x2019,0x2026,
             0x25b3,0x25a1,0x25cb,0xd7,0x2630,0xe000,0xe001,
             0x2191,0x2193,0x2190,0x2192]
controller_codes=set(extra_codes[6:])
data=bytearray(); faces=[]
def controller_glyph(code,size):
    scale=4
    width=round(size*1.8) if code in (0xe000,0xe001) else size
    image=Image.new('L',(width*scale,size*scale))
    draw=ImageDraw.Draw(image)
    left,top,right,bottom=2*scale,2*scale,(width-2)*scale,(size-2)*scale
    middle=size*scale//2
    stroke=max(1,round(size/12))*scale
    if code==0x25b3:
        draw.line([(middle,top),(right,bottom),(left,bottom),(middle,top)],fill=255,width=stroke,joint='curve')
    elif code==0x25a1:
        draw.rectangle((left,top,right,bottom),outline=255,width=stroke)
    elif code==0x25cb:
        draw.ellipse((left,top,right,bottom),outline=255,width=stroke)
    elif code==0xd7:
        draw.line((left,top,right,bottom),fill=255,width=stroke)
        draw.line((left,bottom,right,top),fill=255,width=stroke)
    elif code==0x2630:
        for y in (top,middle,bottom):draw.line((left,y,right,y),fill=255,width=stroke)
    elif code in (0xe000,0xe001):
        draw.rounded_rectangle((left,top,right,bottom),radius=4*scale,outline=255,width=stroke)
        badge_font=ImageFont.truetype(str(font_path),round(size*.65)*scale)
        draw.text((width*scale//2,middle),'L1' if code==0xe000 else 'R1',font=badge_font,anchor='mm',fill=255)
    else:
        # Rotate one arrow to keep all four directions visually consistent.
        draw.line((middle,bottom,middle,top),fill=255,width=stroke)
        draw.line([(left,middle),(middle,top),(right,middle)],fill=255,width=stroke)
        image=image.rotate({0x2191:0,0x2193:180,0x2190:90,0x2192:270}[code])
    return image.resize((width,size),Image.Resampling.LANCZOS)

for size in [20,24,28,32,44,60,76]:
    font=ImageFont.truetype(str(font_path),size)
    font.set_variation_by_axes([600 if size>=32 else 500])
    glyphs=[]
    for code in list(range(32,256))+extra_codes:
        if code in controller_codes:
            image=controller_glyph(code,size)
            width,height=image.size
            glyphs.append((len(data),width,height,0,round(size*.18),width+3))
            data.extend(image.tobytes())
            continue
        c=chr(code); left,top,right,bottom=font.getbbox(c)
        width,height=right-left,bottom-top
        image=Image.new('L',(max(1,width),max(1,height)))
        ImageDraw.Draw(image).text((-left,-top),c,font=font,fill=255)
        glyphs.append((len(data),width,height,left,top,round(font.getlength(c))))
        if width and height:data.extend(image.tobytes())
    faces.append((size,glyphs))
(ROOT/'assets/ui-font.bin').write_bytes(data)
header='''// Generated by tools/build-font.py from Manrope (SIL OFL 1.1).
#pragma once
#include <array>
#include <cstdint>
namespace botty::font {
struct Glyph { unsigned offset; unsigned short width,height; short left,top,advance; };
struct Face { unsigned size; std::array<Glyph,GLYPH_COUNT> glyphs; };
'''
header=header.replace('GLYPH_COUNT',str(224+len(extra_codes)))
header+=f'inline constexpr std::array<unsigned,{len(extra_codes)}> extraCodes{{{{'+','.join(hex(c) for c in extra_codes)+'}};\n'
header+=f'inline constexpr unsigned dataSize={len(data)};\n'
header+='inline constexpr std::array<Face,7> faces{{\n'
for size,glyphs in faces:
    header+=f'    {{{size}, {{{{\n'
    header+=''.join('        {'+','.join(map(str,g))+'},\n' for g in glyphs)
    header+='    }}},\n'
header+='}};\n}\n'
(ROOT/'src/font_data.hpp').write_text(header)
print('Font bytes:',len(data),'source SHA256:',hashlib.sha256(font_path.read_bytes()).hexdigest())
